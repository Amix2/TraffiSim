using Unity.Entities;

public struct RoadSegmentMesherAspect : IAspect
{
    public Entity Entity;
    public DynamicBuffer<LinkedEntityGroup> LinkedEntityGroup;
    public RefRW<RoadSegmentData> Data;
    public DynamicBuffer<RoadSegmentNode> Nodes;
    public DynamicBuffer<RoadSegmentLane> ChildLanes;

    public void ClearAllVisualizers(ref EntityCommandBuffer ecb, EntityManager EntityManager)
    {
        for (int i = 0; i < LinkedEntityGroup.Length; i++)
        {
            if (EntityManager.HasComponent<RoadVisualizerData>(LinkedEntityGroup[i].Value))
            {
                ecb.DestroyEntity(LinkedEntityGroup[i].Value);
                LinkedEntityGroup.RemoveAt(i);
                i--;
            }
        }
    }

    #region <auto-generated-lookup> do not edit; regenerated by GenerateAspectLookups
    /// Entity-only: bind fields afterwards with chained Set(...).
    public RoadSegmentMesherAspect(Entity entity)
    {
        this = default;
        Entity = entity;
    }

    /// Binds every field through temporary lookups. Main-thread use;
    /// prefer declared slots + chained Set(...) inside systems.
    public RoadSegmentMesherAspect(ref SystemState state, Entity entity)
    {
        this = default;
        Entity = entity;
        var linkedEntityGroupLookup = state.GetBufferLookup<LinkedEntityGroup>(isReadOnly: false);
        var roadSegmentDataLookup = state.GetComponentLookup<RoadSegmentData>(isReadOnly: false);
        var roadSegmentNodeLookup = state.GetBufferLookup<RoadSegmentNode>(isReadOnly: false);
        var roadSegmentLaneLookup = state.GetBufferLookup<RoadSegmentLane>(isReadOnly: false);
        LinkedEntityGroup = linkedEntityGroupLookup[entity];
        Data = roadSegmentDataLookup.GetRefRW(entity);
        Nodes = roadSegmentNodeLookup[entity];
        ChildLanes = roadSegmentLaneLookup[entity];
    }

    /// SystemBase / managed system variant.
    public RoadSegmentMesherAspect(SystemBase system, Entity entity)
    {
        this = default;
        Entity = entity;
        var linkedEntityGroupLookup = system.GetBufferLookup<LinkedEntityGroup>(isReadOnly: false);
        var roadSegmentDataLookup = system.GetComponentLookup<RoadSegmentData>(isReadOnly: false);
        var roadSegmentNodeLookup = system.GetBufferLookup<RoadSegmentNode>(isReadOnly: false);
        var roadSegmentLaneLookup = system.GetBufferLookup<RoadSegmentLane>(isReadOnly: false);
        LinkedEntityGroup = linkedEntityGroupLookup[entity];
        Data = roadSegmentDataLookup.GetRefRW(entity);
        Nodes = roadSegmentNodeLookup[entity];
        ChildLanes = roadSegmentLaneLookup[entity];
    }

    // Set(...) overloads. Each returns the aspect, so calls chain:
    //   new RoadSegmentMesherAspect(e).Set(slotA).Set(bufferB);
    // Statement form works too — Set mutates this and returns a copy.

    public RoadSegmentMesherAspect Set(BufferSlot<LinkedEntityGroup> slot)
    {
        LinkedEntityGroup = slot.Bind(Entity);
        return this;
    }

    public RoadSegmentMesherAspect Set(LookupSlot<RoadSegmentData> slot)
    {
        Data = slot.BindRW(Entity);
        return this;
    }

    public RoadSegmentMesherAspect Set(BufferSlot<RoadSegmentNode> slot)
    {
        Nodes = slot.Bind(Entity);
        return this;
    }

    public RoadSegmentMesherAspect Set(BufferSlot<RoadSegmentLane> slot)
    {
        ChildLanes = slot.Bind(Entity);
        return this;
    }

    public RoadSegmentMesherAspect Set(BufferLookup<LinkedEntityGroup> lookup)
    {
        LinkedEntityGroup = lookup[Entity];
        return this;
    }

    public RoadSegmentMesherAspect Set(ComponentLookup<RoadSegmentData> lookup)
    {
        Data = lookup.GetRefRW(Entity);
        return this;
    }

    public RoadSegmentMesherAspect Set(BufferLookup<RoadSegmentNode> lookup)
    {
        Nodes = lookup[Entity];
        return this;
    }

    public RoadSegmentMesherAspect Set(BufferLookup<RoadSegmentLane> lookup)
    {
        ChildLanes = lookup[Entity];
        return this;
    }

    // From IJobEntity Execute parameters.
    public RoadSegmentMesherAspect Set(DynamicBuffer<LinkedEntityGroup> buffer)
    {
        LinkedEntityGroup = buffer;
        return this;
    }
    public RoadSegmentMesherAspect Set(RefRW<RoadSegmentData> value)
    {
        Data = value;
        return this;
    }
    public RoadSegmentMesherAspect Set(DynamicBuffer<RoadSegmentNode> buffer)
    {
        Nodes = buffer;
        return this;
    }
    public RoadSegmentMesherAspect Set(DynamicBuffer<RoadSegmentLane> buffer)
    {
        ChildLanes = buffer;
        return this;
    }
    #endregion </auto-generated-lookup>
}
